#!/usr/bin/env python3
# pcf2font.py OUT FONT.pcf.gz... -- font.h: the printable ASCII of X's
# misc-fixed fonts, which are public domain ("Public domain font. Share
# and enjoy."), for text() and the help pages, which X drew with its fonts.
# Run once by hand, where xfonts-base is; font.h is committed.
import gzip, struct, sys


def pcf(path):
    d = gzip.open(path).read()
    if d[:4] != b'\x01fcp':
        raise SystemExit(path + ': not a PCF font')
    n = struct.unpack('<I', d[4:8])[0]
    tab = {}
    for i in range(n):
        t, fmt, size, off = struct.unpack('<IIII', d[8 + i * 16:24 + i * 16])
        tab[t] = off

    def fmt_at(off):
        f = struct.unpack('<I', d[off:off + 4])[0]
        return f, '>' if f & 4 else '<'
    # accelerators: ascent and descent follow the seven flag bytes and an
    # eighth of padding
    off = tab.get(0x100, tab[2])
    f, e = fmt_at(off)
    asc, desc = struct.unpack(e + 'ii', d[off + 4 + 8:off + 4 + 8 + 8])
    # metrics: the character cell's width, from a glyph's
    off = tab[4]
    f, e = fmt_at(off)
    if f & 0x100:
        width = d[off + 6 + 2] - 0x80
    else:
        width = struct.unpack(e + 'h', d[off + 8 + 4:off + 8 + 6])[0]
    # bitmaps
    off = tab[8]
    f, e = fmt_at(off)
    count = struct.unpack(e + 'I', d[off + 4:off + 8])[0]
    offs = struct.unpack(e + '%dI' % count, d[off + 8:off + 8 + 4 * count])
    pad = 1 << (f & 3)
    base = off + 8 + 4 * count + 16
    # encodings
    off = tab[0x20]
    f2, e2 = fmt_at(off)
    c1, c2, r1, r2, dflt = struct.unpack(e2 + '5h', d[off + 4:off + 14])
    total = (c2 - c1 + 1) * (r2 - r1 + 1)
    idx = struct.unpack(e2 + '%dH' % total, d[off + 14:off + 14 + 2 * total])
    h = asc + desc
    per = (width + 7) // 8
    rowbytes = (per + pad - 1) // pad * pad
    glyphs = []
    for ch in range(32, 127):
        o = base + offs[idx[ch - c1]]
        rows = []
        for y in range(h):
            r = d[o + y * rowbytes:o + y * rowbytes + per]
            v = 0
            for b in r:
                v = v << 8 | b
            # bit 15 is the leftmost pixel
            rows.append(v << (16 - 8 * per))
        glyphs.append(rows)
    return width, asc, desc, glyphs


out = sys.argv[1]
with open(out, 'w') as f:
    f.write('/* font.h -- generated by c4/pcf2font.py from the misc-fixed fonts of X.\n')
    f.write('   Those fonts say: "Public domain font.  Share and enjoy."\n')
    f.write('   Each glyph is rows of 16 bits, the leftmost pixel in the top bit. */\n')
    names = []
    for i, path in enumerate(sys.argv[2:]):
        w, a, de, glyphs = pcf(path)
        names.append((i, w, a, de))
        f.write('/* %s: %dx%d, ascent %d, descent %d */\n' % (path.split('/')[-1], w, a + de, a, de))
        f.write('static const unsigned short font_%d[] = {\n' % i)
        for g in glyphs:
            f.write(','.join('0x%x' % v for v in g) + ',\n')
        f.write('};\n')
    f.write('#define ACE_FONTS %d\n' % len(names))
    f.write('static const unsigned short *font_rows[] = {%s};\n' % ','.join('font_%d' % n[0] for n in names))
    f.write('static const int font_w[] = {%s};\n' % ','.join(str(n[1]) for n in names))
    f.write('static const int font_ascent[] = {%s};\n' % ','.join(str(n[2]) for n in names))
    f.write('static const int font_descent[] = {%s};\n' % ','.join(str(n[3]) for n in names))
