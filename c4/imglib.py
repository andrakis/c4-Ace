#!/usr/bin/env python3
# imglib.py -n BASE -i DIR OUT NAME... -- what upstream's make-imglib does,
# for a c4 build, where no libpng runs: the PNGs in DIR whose names begin
# NAME., or NAME.png, decoded on the host and written as C, each image as
# run-length colour indices with its own palette (xwin-c4.c reads them).
# A NAME may be "NAME ACROSS DOWN", as lib/images.in lists them, or
# "@FILE" for such a list. Python's standard library only.
import glob, os, struct, sys, zlib


def png(path):
    """(w, h, bit depth, colour type, rows of (r, g, b, opaque))"""
    d = open(path, 'rb').read()
    if d[:8] != b'\x89PNG\r\n\x1a\n':
        raise SystemExit(path + ': not a PNG')
    p, idat, pal, trns = 8, [], [], b''
    while p < len(d):
        n, t = struct.unpack('>I4s', d[p:p + 8])
        c = d[p + 8:p + 8 + n]
        p += 12 + n
        if t == b'IHDR':
            w, h, depth, ctype, _, _, ilace = struct.unpack('>IIBBBBB', c)
        elif t == b'IDAT':
            idat.append(c)
        elif t == b'PLTE':
            pal = [tuple(c[i:i + 3]) for i in range(0, len(c), 3)]
        elif t == b'tRNS':
            trns = c
    if ilace:
        raise SystemExit(path + ': interlaced, which no image of Ace is')
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    bpp = max(1, channels * depth // 8)
    stride = (w * channels * depth + 7) // 8
    raw, q, prev, rows = zlib.decompress(b''.join(idat)), 0, bytes(stride), []
    for y in range(h):
        f = raw[q]
        line = bytearray(raw[q + 1:q + 1 + stride])
        q += 1 + stride
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        prev = bytes(line)
        row = []
        for x in range(w):
            if depth < 8:
                v = (line[x * depth // 8] >> (8 - depth - x * depth % 8)) & ((1 << depth) - 1)
            else:
                v = line[x * bpp]
            if ctype == 3:
                row.append(pal[v] + (v >= len(trns) or trns[v] > 128,))
            elif ctype == 0:
                # as upstream's cvt_gt: a shallow grey is shifted, not scaled
                v = v << (8 - depth) if depth < 8 else v
                row.append((v, v, v, True))
            elif ctype == 4:
                row.append((v, v, v, line[x * bpp + depth // 8] > 128))
            else:
                r, g, b = line[x * bpp], line[x * bpp + depth // 8], line[x * bpp + 2 * depth // 8]
                a = line[x * bpp + 3 * depth // 8] if ctype == 6 else 255
                row.append((r, g, b, a > 128))
        rows.append(row)
    return w, h, depth, ctype, rows


def encode(rows):
    """npal (2 bytes), the palette's r g b, has-mask, then runs: count (1 to
    255), index. A pixel that shows through has index npal."""
    pal, runs, last, n, mask = {}, bytearray(), None, 0, 0
    for row in rows:
        for r, g, b, opaque in row:
            if opaque:
                i = pal.setdefault((r, g, b), len(pal))
            else:
                i, mask = 255, 1
            if i == last and n < 255:
                n += 1
            else:
                if n:
                    runs += bytes((n, last))
                last, n = i, 1
    runs += bytes((n, last))
    if len(pal) > 255:
        raise SystemExit('more than 255 colours in an image')
    head = bytearray(struct.pack('<H', len(pal)))
    for r, g, b in pal:
        head += bytes((r, g, b))
    head.append(mask)
    # the see-through index, written as 255 above, is npal
    for i in range(1, len(runs), 2):
        if runs[i] == 255:
            runs[i] = len(pal)
    return head + runs


args = sys.argv[1:]
base, idir = 'images', '.'
while args and args[0].startswith('-'):
    if args[0] == '-n':
        base = args[1]
    elif args[0] == '-i':
        idir = args[1]
    args = args[2:]
out, names = args[0], []
for a in args[1:]:
    if a.startswith('@'):
        names += [l.split() for l in open(a[1:]) if l.strip()]
    else:
        names.append(a.split())

lines = ['/* Automatically generated by c4/imglib.py, do not edit */', '#include "imagelib.h"', '']
listed, index = [], 0
for name in names:
    stem = name[0][:-4] if name[0].endswith('.png') else name[0]
    across, down = (int(name[1]), int(name[2])) if len(name) > 2 else (1, 1)
    files = sorted(glob.glob(os.path.join(idir, stem + '.png')) + glob.glob(os.path.join(idir, stem + '.*.png')))
    subs = {0: [], 1: [], 2: []}
    for f in files:
        w, h, depth, ctype, rows = png(f)
        # as make-imglib: mono, grey or colour by the file's format
        kind = 0 if depth == 1 else 2 if ctype & 2 else 1
        data = encode(rows)
        lines.append('/* %s, %dx%d */' % (os.path.basename(f), w, h))
        lines.append('static const unsigned char data_%d[] = {' % index)
        for i in range(0, len(data), 24):
            lines.append(','.join(map(str, data[i:i + 24])) + ',')
        lines.append('};')
        subs[kind].append((w, h, index))
        index += 1
    sub_names = []
    for kind in (0, 1, 2):
        if subs[kind]:
            n = 'sub_%d_%d' % (len(listed), kind)
            lines.append('static image %s[] = {' % n)
            lines += ['  { %d, %d, data_%d },' % s for s in subs[kind]]
            lines += ['  { 0, 0, 0 }', '};']
            sub_names.append(n)
        else:
            sub_names.append('0')
    listed.append('  { "%s", %d, %d, { %s } },' % (stem, across, down, ', '.join(sub_names)))
lines.append('image_list %s_imagelib[] = {' % base)
lines += listed
lines += ['  { 0, 0, 0, { 0, 0, 0 } }', '};', '']
open(out, 'w').write('\n'.join(lines))
