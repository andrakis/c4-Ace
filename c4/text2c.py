#!/usr/bin/env python3
# text2c.py NAME IN OUT -- upstream's lib/text2c, for a c4 build: the file
# as a char array, ended by a zero.
import sys
name, src, out = sys.argv[1:4]
d = open(src, 'rb').read()
with open(out, 'w') as f:
    f.write("/* Generated by c4/text2c.py from %s: its copyright is that file's */\n" % src.split('/')[-1])
    f.write('char %s[] = {\n' % name)
    for i in range(0, len(d), 24):
        f.write(','.join(map(str, d[i:i + 24])) + ',\n')
    f.write('0 };\n')
